// Generate tools/body_map/body.svg (and the phone app's copy) from react-native-body-highlighter's MIT-licensed
// male front/back polygons, using muscle_map.json to tag each polygon with our muscle ids.
//   cd tools && npm install && npm run body
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const { bodyFront } = require("react-native-body-highlighter/dist/assets/bodyFront.js");
const { bodyBack } = require("react-native-body-highlighter/dist/assets/bodyBack.js");
const map = JSON.parse(readFileSync(join(here, "muscle_map.json"), "utf8"));
const version = require("react-native-body-highlighter/package.json").version;

// Figure bounds in the library's coordinates (front 0–724, back 724–1448), trimmed to the drawn body.
const VIEWS = {
  front: { data: bodyFront, x: 30, y: 60, w: 664, h: 1330 },
  back: { data: bodyBack, x: 754, y: 60, w: 664, h: 1330 },
};

const esc = (s) => s.replace(/"/g, "&quot;");
const lines = [];
let muscles = 0;
for (const [view, v] of Object.entries(VIEWS)) {
  lines.push(`  <g id="${view}" data-x="${v.x}" data-y="${v.y}" data-width="${v.w}" data-height="${v.h}">`);
  const viewMap = map[view];
  for (const part of v.data) {
    const pieces = (side) => part.path[side] || [];
    if (map.parts.includes(part.slug)) {
      const d = [...pieces("common"), ...pieces("left"), ...pieces("right")].join(" ");
      lines.push(`    <path class="part" data-slug="${part.slug}" data-view="${view}" d="${esc(d)}"/>`);
      continue;
    }
    const m = viewMap[part.slug];
    if (m === undefined) throw new Error(`${view}/${part.slug} is not in muscle_map.json`);
    // group polygons by the id list they map to
    const groups = new Map();
    const add = (ids, d) => {
      const key = ids.join(" ");
      groups.set(key, [...(groups.get(key) || []), d]);
    };
    for (const side of ["common", "left", "right"]) {
      pieces(side).forEach((d, i) => add(Array.isArray(m) ? m : (m[side] || m)[String(i)] || [], d));
    }
    for (const [ids, ds] of groups) {
      lines.push(`    <path class="muscle" data-slug="${part.slug}" data-ids="${ids}" data-view="${view}" d="${esc(ds.join(" "))}"/>`);
      muscles++;
    }
  }
  lines.push("  </g>");
}

const { x, y, h } = VIEWS.front;
const width = VIEWS.back.x + VIEWS.back.w - x;
const svg = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Body map generated by tools/body_map/make_body.mjs — do not edit by hand.
     Polygons: react-native-body-highlighter ${version} (MIT, (c) 2022 ELABBASSI Hicham), see CREDITS.md.
     Each muscle path carries data-ids = our muscle ids (PLAN.md §4.5), mapped in muscle_map.json. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${x} ${y} ${width} ${h}" width="${Math.round(width / 4)}" height="${Math.round(h / 4)}">
  <style>
    .part { fill: #191C25; stroke: #343B4D; stroke-width: 2; }
    .muscle { fill: #232836; stroke: #343B4D; stroke-width: 2; }
  </style>
${lines.join("\n")}
</svg>
`;
for (const out of [join(here, "body.svg"), join(here, "../../backend/public/app/body.svg")]) writeFileSync(out, svg);
console.log(`body.svg: ${muscles} muscle paths, viewBox ${x} ${y} ${width} ${h}`);
