"""Helpers to emit LVGL 9 image descriptors (lv_image_dsc_t) as C source. Shared by the asset converters."""
from __future__ import annotations

LVGL_CF = {"A8": "LV_COLOR_FORMAT_A8", "ARGB8888": "LV_COLOR_FORMAT_ARGB8888", "RGB565": "LV_COLOR_FORMAT_RGB565"}
BPP = {"A8": 1, "ARGB8888": 4, "RGB565": 2}


def c_bytes(data: bytes, per_line: int = 24) -> str:
    rows = (", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) for i in range(0, len(data), per_line))
    return ",\n    ".join(rows)


def image_c(name: str, w: int, h: int, cf: str, data: bytes) -> str:
    """A `const lv_image_dsc_t <name>` plus its pixel array. `data` must be w*h*bpp bytes, row-major."""
    stride = w * BPP[cf]
    assert len(data) == stride * h, (name, len(data), stride * h)
    return (
        f"static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {name}_map[] = {{\n    {c_bytes(data)}\n}};\n\n"
        f"const lv_image_dsc_t {name} = {{\n"
        f"    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = {LVGL_CF[cf]}, .flags = 0,\n"
        f"                .w = {w}, .h = {h}, .stride = {stride} }},\n"
        f"    .data_size = sizeof({name}_map),\n"
        f"    .data = {name}_map,\n"
        f"}};\n\n"
    )


GENERATED = "/* Generated by {tool} — do not edit by hand. */\n"
