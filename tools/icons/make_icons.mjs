// Copy the Material Symbols we use (Apache-2.0, see CREDITS.md) into tools/icons/svg/ and emit the phone app's
// icon module. The desk screen's LVGL masks are rendered from the same SVGs by tools/hud_assets/make_hud_assets.py.
//   cd tools && npm install && npm run icons
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("@material-symbols/svg-400/package.json"));
const version = require("@material-symbols/svg-400/package.json").version;

// Style: Rounded, filled, weight 400.
export const ICONS = [
  // splits + rest days
  "fitness_center", "rowing", "directions_run", "hot_tub", "bedtime",
  // habits
  "nutrition", "no_food", "timer", "directions_walk", "wb_sunny", "dark_mode", "menu_book",
  // UI
  "home", "monitor_heart", "calendar_month", "history", "check", "close", "local_fire_department",
  "bolt", "add", "remove", "undo", "favorite", "trophy", "water_drop",
  // vitals
  "ecg_heart", "spo2",
];

mkdirSync(join(here, "svg"), { recursive: true });
const paths = {};
for (const name of ICONS) {
  const svg = readFileSync(join(pkgDir, "rounded", `${name}-fill.svg`), "utf8");
  writeFileSync(join(here, "svg", `${name}.svg`), svg);
  paths[name] = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]).join(" ");
}
const js = `// Generated by tools/icons/make_icons.mjs — Material Symbols Rounded (fill) ${version}, Apache-2.0. See CREDITS.md.
// viewBox "0 -960 960 960"
window.MS_ICONS = ${JSON.stringify(paths, null, 0).replace(/","/g, '",\n  "')};
`;
writeFileSync(join(here, "../../backend/public/app/icons.js"), js);
console.log(`${ICONS.length} icons → tools/icons/svg/ and backend/public/app/icons.js`);
