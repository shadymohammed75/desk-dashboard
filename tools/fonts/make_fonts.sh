#!/usr/bin/env bash
# Generate the LVGL fonts for the desk screen from Inter (SIL Open Font License 1.1, see CREDITS.md) — the same
# typeface as the phone app. The built-in LVGL fonts lack "—" (missing data) and "·" (separators), so we build our own.
#
#   (cd tools && npm install) && tools/fonts/make_fonts.sh    → firmware/ui/fonts/font_*.c + fonts.h
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/firmware/ui/fonts"
FONTS="$ROOT/tools/node_modules/@fontsource/inter/files"   # @fontsource/inter 5.3.0 (pinned in tools/package.json)
CONV="lv_font_conv@1.5.3"
[ -d "$FONTS" ] || { echo "Run 'npm install' in tools/ first"; exit 1; }
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
cp "$FONTS/inter-latin-600-normal.woff" "$TMP/SemiBold.woff"
cp "$FONTS/inter-latin-700-normal.woff" "$TMP/Bold.woff"
cp "$FONTS/inter-latin-800-normal.woff" "$TMP/ExtraBold.woff"

ASCII="0x20-0x7E"
EXTRA="0xB7,0x2013,0x2014"                 # · – —
DIGITS="0x20,0x25,0x2B-0x3A,0x2014"        # space % + , - . / 0-9 : —
CAPS="0x20-0x5F,$EXTRA"                    # punctuation, digits, A–Z

gen() { # name weight size range
  npx -y "$CONV" --bpp 4 --size "$3" --no-compress --font "$TMP/$2.woff" --range "$4" \
      --format lvgl --lv-include lvgl.h --lv-font-name "$1" -o "$OUT/$1.c" >/dev/null
  sed -i -e "s#$TMP/#Inter-#" -e "s#$ROOT/##" "$OUT/$1.c"   # keep the output deterministic
  echo "  $1 ($2 $3px)"
}

mkdir -p "$OUT"
echo "Generating fonts → $OUT"
gen font_12 SemiBold 12 "$ASCII,$EXTRA"
gen font_14 SemiBold 14 "$ASCII,$EXTRA"
gen font_16 Bold 16 "$ASCII,$EXTRA"
gen font_20 SemiBold 20 "$ASCII,$EXTRA"
gen font_28 ExtraBold 28 "$ASCII,$EXTRA"
gen font_36 ExtraBold 36 "$DIGITS"
gen font_48 ExtraBold 48 "$CAPS"

cat > "$OUT/fonts.h" <<'H'
/* Generated by tools/fonts/make_fonts.sh — Inter (OFL 1.1). */
#pragma once
#include "lvgl.h"

LV_FONT_DECLARE(font_12)   /* SemiBold: labels */
LV_FONT_DECLARE(font_14)   /* SemiBold: small text */
LV_FONT_DECLARE(font_16)   /* Bold: HUD text */
LV_FONT_DECLARE(font_20)   /* SemiBold: coach line */
LV_FONT_DECLARE(font_28)   /* ExtraBold: values, titles */
LV_FONT_DECLARE(font_36)   /* ExtraBold, digits only: blood pressure */
LV_FONT_DECLARE(font_48)   /* ExtraBold, caps + digits: score, celebration */
H
echo "done"
