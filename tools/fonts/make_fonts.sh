#!/usr/bin/env bash
# Generate the LVGL fonts for the desk screen from Montserrat (SIL Open Font License 1.1).
# The built-in LVGL fonts lack "—" (missing data) and "·" (separators), so we build our own.
#
#   tools/fonts/make_fonts.sh        → firmware/ui/fonts/font_*.c + fonts.h
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/firmware/ui/fonts"
MONTSERRAT_REV="555facfb2a18c72c3c0380f0d9c0f060453a9058"   # JulietaUla/Montserrat, pinned
CONV="lv_font_conv@1.5.3"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

for w in SemiBold Bold; do
  curl -sSfL -o "$TMP/$w.ttf" "https://raw.githubusercontent.com/JulietaUla/Montserrat/$MONTSERRAT_REV/fonts/ttf/Montserrat-$w.ttf"
done

ASCII="0x20-0x7E"
EXTRA="0xB7,0x2013,0x2014"                 # · – —
DIGITS="0x20,0x25,0x2B-0x3A,0x2014"        # space % + , - . / 0-9 : —
CAPS="0x20-0x5F,$EXTRA"                    # punctuation, digits, A–Z

gen() { # name weight size range
  npx -y "$CONV" --bpp 4 --size "$3" --no-compress --font "$TMP/$2.ttf" --range "$4" \
      --format lvgl --lv-include lvgl.h --lv-font-name "$1" -o "$OUT/$1.c" >/dev/null
  sed -i -e "s#$TMP/#Montserrat-#" -e "s#$ROOT/##" "$OUT/$1.c"   # keep the output deterministic
  echo "  $1 ($2 $3px)"
}

mkdir -p "$OUT"
echo "Generating fonts → $OUT"
gen font_12 SemiBold 12 "$ASCII,$EXTRA"
gen font_14 SemiBold 14 "$ASCII,$EXTRA"
gen font_16 Bold 16 "$ASCII,$EXTRA"
gen font_20 SemiBold 20 "$ASCII,$EXTRA"
gen font_28 Bold 28 "$ASCII,$EXTRA"
gen font_36 Bold 36 "$DIGITS"
gen font_48 Bold 48 "$CAPS"

cat > "$OUT/fonts.h" <<'H'
/* Generated by tools/fonts/make_fonts.sh — Montserrat (OFL 1.1). */
#pragma once
#include "lvgl.h"

LV_FONT_DECLARE(font_12)   /* SemiBold: labels */
LV_FONT_DECLARE(font_14)   /* SemiBold: small text */
LV_FONT_DECLARE(font_16)   /* Bold: HUD text */
LV_FONT_DECLARE(font_20)   /* SemiBold: coach line */
LV_FONT_DECLARE(font_28)   /* Bold: values, titles */
LV_FONT_DECLARE(font_36)   /* Bold, digits only: blood pressure */
LV_FONT_DECLARE(font_48)   /* Bold, caps + digits: score, celebration */
H
echo "done"
